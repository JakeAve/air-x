// Regenerates src/lib/fountain/seeds.ts: for each padded size, the smallest
// seed whose source system is invertible. Run after any change to raptor.ts
// rows, and bump PROTOCOL_VERSION. `deno run -A scripts/raptor-seeds.ts`
import {
  dataBytes,
  MAX_BUNDLE_BYTES,
  SOUND_PACKET_BYTES,
} from "@/lib/protocol.ts";
import { invertible, padSize } from "@/lib/fountain/raptor.ts";

const maxK = Math.ceil(
  MAX_BUNDLE_BYTES / dataBytes(SOUND_PACKET_BYTES, 256),
);

if (import.meta.main) {
  const seeds: number[] = [];
  for (let i = 0; padSize(i - 1) < maxK || i === 0; i++) {
    const kPad = padSize(i);
    let seed = 0;
    while (!invertible(kPad, seed)) seed++;
    seeds.push(seed);
    console.error(`${kPad}: ${seed}`);
  }
  await Deno.writeTextFile(
    new URL("../src/lib/fountain/seeds.ts", import.meta.url),
    `// Generated by scripts/raptor-seeds.ts: per padded size (raptor.ts padSize),\n` +
      `// the smallest seed whose source system is invertible.\n` +
      `// deno-fmt-ignore\n` +
      `export const SEEDS: number[] = [\n${
        seeds.join(", ").replace(/(.{1,78})(, |$)/g, "  $1,\n")
      }];\n`,
  );
}
